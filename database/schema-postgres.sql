
-- PeopleDesk PostgreSQL Database Schema
-- Database: Neon PostgreSQL

-- 1. Departments
CREATE TABLE IF NOT EXISTS departments (
    department_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(100) NOT NULL UNIQUE,
    location VARCHAR(100),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Jobs
CREATE TABLE IF NOT EXISTS jobs (
    job_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_title VARCHAR(100) NOT NULL UNIQUE,
    job_description VARCHAR(255)
);

-- 3. Users
CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(10) NOT NULL DEFAULT 'hr'
        CHECK (role IN ('admin', 'hr')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 4. Employees
CREATE TABLE IF NOT EXISTS employees (
    emp_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    phone VARCHAR(20),
    hire_date DATE NOT NULL,
    department_id INTEGER NOT NULL,
    job_id INTEGER NOT NULL,
    base_salary NUMERIC(12,2) NOT NULL
        CHECK (base_salary >= 0),
    employment_status VARCHAR(20) NOT NULL DEFAULT 'Active'
        CHECK (employment_status IN ('Active', 'Inactive', 'On Leave')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_employee_department
        FOREIGN KEY (department_id)
        REFERENCES departments(department_id),

    CONSTRAINT fk_employee_job
        FOREIGN KEY (job_id)
        REFERENCES jobs(job_id)
);

-- 5. Attendance
CREATE TABLE IF NOT EXISTS attendance (
    attendance_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id INTEGER NOT NULL,
    attendance_date DATE NOT NULL,
    check_in TIME,
    check_out TIME,
    attendance_status VARCHAR(30) NOT NULL
        CHECK (attendance_status IN (
            'Present', 'Absent', 'Half Day', 'Work From Home'
        )),

    CONSTRAINT uq_attendance_employee_date
        UNIQUE (emp_id, attendance_date),

    CONSTRAINT chk_attendance_time
        CHECK (
            check_in IS NULL
            OR check_out IS NULL
            OR check_out >= check_in
        ),

    CONSTRAINT fk_attendance_employee
        FOREIGN KEY (emp_id)
        REFERENCES employees(emp_id)
        ON DELETE CASCADE
);

-- 6. Leave Requests
CREATE TABLE IF NOT EXISTS leave_requests (
    leave_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id INTEGER NOT NULL,
    leave_type VARCHAR(20) NOT NULL
        CHECK (leave_type IN ('Casual', 'Sick', 'Annual', 'Unpaid')),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    reason VARCHAR(500),
    leave_status VARCHAR(20) NOT NULL DEFAULT 'Pending'
        CHECK (leave_status IN ('Pending', 'Approved', 'Rejected')),
    applied_on DATE NOT NULL DEFAULT CURRENT_DATE,
    reviewed_at TIMESTAMP,

    CONSTRAINT chk_leave_dates
        CHECK (end_date >= start_date),

    CONSTRAINT fk_leave_employee
        FOREIGN KEY (emp_id)
        REFERENCES employees(emp_id)
        ON DELETE CASCADE
);

-- 7. Payroll
CREATE TABLE IF NOT EXISTS payroll (
    payroll_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id INTEGER NOT NULL,
    payroll_month DATE NOT NULL,
    basic_salary NUMERIC(12,2) NOT NULL,
    allowances NUMERIC(12,2) NOT NULL DEFAULT 0,
    deductions NUMERIC(12,2) NOT NULL DEFAULT 0,

    net_salary NUMERIC(12,2)
        GENERATED ALWAYS AS (
            basic_salary + allowances - deductions
        ) STORED,

    payment_date DATE,
    payment_status VARCHAR(20) NOT NULL DEFAULT 'Pending'
        CHECK (payment_status IN ('Pending', 'Paid', 'Failed')),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_payroll_employee_month
        UNIQUE (emp_id, payroll_month),

    CONSTRAINT chk_payroll_amounts
        CHECK (
            basic_salary >= 0
            AND allowances >= 0
            AND deductions >= 0
            AND basic_salary + allowances >= deductions
        ),

    CONSTRAINT chk_payroll_month
        CHECK (EXTRACT(DAY FROM payroll_month) = 1),

    CONSTRAINT fk_payroll_employee
        FOREIGN KEY (emp_id)
        REFERENCES employees(emp_id)
);

-- 8. Salary History
CREATE TABLE IF NOT EXISTS salary_history (
    history_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id INTEGER NOT NULL,
    old_salary NUMERIC(12,2) NOT NULL,
    new_salary NUMERIC(12,2) NOT NULL,
    effective_date DATE NOT NULL,
    change_reason VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_salary_history_employee
        FOREIGN KEY (emp_id)
        REFERENCES employees(emp_id)
        ON DELETE CASCADE
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_employee_department
    ON employees(department_id);

CREATE INDEX IF NOT EXISTS idx_employee_job
    ON employees(job_id);

CREATE INDEX IF NOT EXISTS idx_attendance_date
    ON attendance(attendance_date);

CREATE INDEX IF NOT EXISTS idx_leave_status
    ON leave_requests(leave_status);

CREATE INDEX IF NOT EXISTS idx_payroll_month
    ON payroll(payroll_month);

CREATE INDEX IF NOT EXISTS idx_salary_history_employee
    ON salary_history(emp_id);

-- Salary History Trigger Function
CREATE OR REPLACE FUNCTION record_employee_salary_history()
RETURNS TRIGGER AS $$
BEGIN
    IF OLD.base_salary IS DISTINCT FROM NEW.base_salary THEN
        INSERT INTO salary_history (
            emp_id,
            old_salary,
            new_salary,
            effective_date,
            change_reason
        )
        VALUES (
            NEW.emp_id,
            OLD.base_salary,
            NEW.base_salary,
            CURRENT_DATE,
            'Salary updated'
        );
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Salary History Trigger
DROP TRIGGER IF EXISTS trg_employee_salary_history
ON employees;

CREATE TRIGGER trg_employee_salary_history
AFTER UPDATE ON employees
FOR EACH ROW
EXECUTE FUNCTION record_employee_salary_history();
